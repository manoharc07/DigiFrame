# Regenerates DigiFrame/lang_data.h from lang/*.json - the UI string tables
# embedded in app flash and parsed once at boot by i18nInit() (i18n.h).
# Run after editing anything in lang/, then rebuild.
#
# en.json is the reference: it is language 0 (the fallback for any missing
# key) and every other file must carry exactly its key set. panel.* values
# must be ASCII, because the panel's built-in 5x7 font is CP437 and prints
# UTF-8 umlauts as garbage. tests/test_lang.py checks the same rules, plus
# matching placeholders, and that this file was regenerated.
$ErrorActionPreference = 'Stop'
$fw   = Split-Path $PSScriptRoot -Parent          # the firmware/ folder
$utf8 = New-Object System.Text.UTF8Encoding($false)
$files = @(Get-Item (Join-Path $fw 'lang\en.json')) +
         @(Get-ChildItem (Join-Path $fw 'lang\*.json') | Where-Object Name -ne 'en.json' | Sort-Object Name)

$refKeys = $null
$langs = @()
foreach ($f in $files) {
  $text = [System.IO.File]::ReadAllText($f.FullName, $utf8)
  if ($text.Contains(')LJSON"')) { throw "$($f.Name): contains the raw-literal terminator )LJSON`"" }
  $obj  = $text | ConvertFrom-Json
  $keys = @($obj.PSObject.Properties | ForEach-Object Name | Sort-Object)
  foreach ($p in $obj.PSObject.Properties) {
    if ($p.Name.StartsWith('panel.') -and $p.Value -match '[^\x20-\x7E]') {
      throw "$($f.Name): $($p.Name) is not ASCII - the panel font cannot draw it"
    }
  }
  if ($null -eq $refKeys) { $refKeys = $keys }
  else {
    $diff = Compare-Object $refKeys $keys
    if ($diff) {
      $msg = ($diff | ForEach-Object { if ($_.SideIndicator -eq '<=') { "missing $($_.InputObject)" } else { "extra $($_.InputObject)" } }) -join ', '
      throw "$($f.Name): key set differs from en.json: $msg"
    }
  }
  $langs += [pscustomobject]@{ Code = $f.BaseName; Ident = 'LANG_JSON_' + $f.BaseName.ToUpper(); Text = $text.TrimEnd() }
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('/* AUTO-GENERATED by firmware/tools/make_lang.ps1 from firmware/lang/*.json')
[void]$sb.AppendLine(' * - do not edit by hand. DigiFrame UI string tables; parsed once at boot by')
[void]$sb.AppendLine(' * i18nInit() (i18n.h). Language 0 is English, the fallback for every key. */')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('')
foreach ($l in $langs) {
  [void]$sb.AppendLine("static const char $($l.Ident)[] PROGMEM = R`"LJSON(" + $l.Text + ")LJSON`";")
  [void]$sb.AppendLine('')
}
[void]$sb.AppendLine('#define LANG_COUNT ' + $langs.Count)
[void]$sb.AppendLine('static const char *const LANG_CODES[LANG_COUNT] = { ' + (($langs | ForEach-Object { "`"$($_.Code)`"" }) -join ', ') + ' };')
[void]$sb.AppendLine('static const char *const LANG_JSON[LANG_COUNT]  = { ' + (($langs | ForEach-Object { $_.Ident }) -join ', ') + ' };')
$out = Join-Path $fw 'DigiFrame\lang_data.h'
[System.IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), $utf8)
Write-Host "wrote $out ($($langs.Count) languages, $($refKeys.Count) keys)"
